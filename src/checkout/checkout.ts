// ── Inputs ───────────────────────────────────────────────────────────────────

export const addressSchema = z.object({
  fullName: z.string().trim().min(2, "Enter the recipient's full name.").max(100),
  line1: z.string().trim().min(3, "Enter a street address.").max(200),
  line2: z.string().trim().max(200).optional().default(""),
  city: z.string().trim().min(2, "Enter a city.").max(100),
  region: z.string().trim().max(100).optional().default(""),
  postalCode: z.string().trim().min(2, "Enter a postal code.").max(20),
  country: z.string().trim().regex(/^[A-Z]{2}$/, "Choose a country."),
  phone: z.string().trim().max(30).optional().default(""),
});
export type Address = z.infer<typeof addressSchema>;

export const quoteInputSchema = z.object({
  country: z.string().regex(/^[A-Z]{2}$/),
  region: z.string().max(100).optional().default(""),
  rateId: z.string().max(40).optional(),
  email: z.email().optional(),
});

export const placeOrderSchema = z.object({
  /** Idempotency key generated by the checkout page (one per checkout attempt). */
  checkoutKey: z.string().regex(/^[A-Za-z0-9_-]{16,64}$/),
  email: z.email("Enter a valid email address.").max(254),
  shippingAddress: addressSchema,
  billingAddress: addressSchema.nullable().optional(),
  rateId: z.string().min(1).max(40),
  paymentMethod: z.string().regex(/^[a-z0-9_]{2,30}$/),
  /** The total the shopper saw; if prices moved since, placement stops and re-quotes. */
  expectedTotalCents: z.number().int().min(0),
  /** The currency of expectedTotalCents; placement re-quotes if the shopper's currency changed. */
  expectedCurrency: z.string().regex(/^[A-Z]{3}$/).optional(),
  saveAddress: z.boolean().optional().default(false),
  notes: z.string().max(500).optional(),
});

// ── Zones and tax ────────────────────────────────────────────────────────────

/**
 * The zone that lists the country, else the "rest of world" (*) zone. The first
 * zone is the store's home market: product "free shipping" applies there only.
 */
async function zoneFor(country: string) {
  const zones = await prisma.shippingZone.findMany({
    orderBy: { position: "asc" },
    select: { id: true, name: true, countries: true, rates: { where: { isActive: true }, orderBy: [{ position: "asc" }], select: { id: true, name: true, priceCents: true, freeOverCents: true, minSubtotalCents: true, etaMinDays: true, etaMaxDays: true } } },
  });
  const zone = zones.find((z) => z.countries.includes(country)) ?? zones.find((z) => z.countries.includes("*")) ?? null;
  return zone ? { ...zone, isHome: zone.id === zones[0]?.id } : null;
}

async function taxFor(country: string, region: string) {
  const rates = await prisma.taxRate.findMany({ where: { country }, orderBy: { priority: "desc" } });
  const r = rates.find((t) => t.region && region && t.region.toUpperCase() === region.trim().toUpperCase()) ?? rates.find((t) => !t.region);
  return r ? { name: r.name, rateBps: r.rateBps, includeShipping: r.includeShipping } : null;
}

// ── Quote ────────────────────────────────────────────────────────────────────

export type Quote = {
  /** The currency every amount is in (the shopper's choice, else the store's). */
  currency: string;
  /** Units of `currency` per 1 unit of the base currency. */
  exchangeRate: number;
  lines: CartLine[];
  unavailable: CartLine[];
  rates: Array<{ id: string; name: string; priceCents: number; etaMinDays: number; etaMaxDays: number }>;
  rateId: string | null;
  totals: Totals;
  tax: { name: string; rateBps: number } | null;
  paymentMethods: Array<{ id: string; label: string; description: string }>;
  shipsTo: boolean;
};

/** Everything checkout needs for an address and (optional) shipping choice. */
export async function quote(owner: CartOwner, input: z.infer<typeof quoteInputSchema>): Promise<Quote> {
  const [{ site, ctx }, cart] = await Promise.all([currencyFor(owner), findCart(owner)]);
  const all = cart ? (await loadLines(cart.id)).map((l) => convertLine(l, ctx)) : [];
  const active = all.filter((l) => !l.savedForLater);
  const lines = active.filter((l) => l.available);
  const unavailable = active.filter((l) => !l.available);
  const tl = toTotalsLines(lines);
  const subtotal = tl.reduce((s, l) => s + l.unitPriceCents * l.quantity, 0);

  const [zone, tax, coupon] = await Promise.all([
    zoneFor(input.country),
    taxFor(input.country, input.region),
    cart?.couponCode ? loadCoupon(cart.couponCode, new Date(), input.email) : Promise.resolve(null),
  ]);
  const offered = (zone?.rates ?? []).map((r) => convertRate(r, ctx)).filter((r) => rateAvailable(r, subtotal));
  const cheapest = offered.reduce<(typeof offered)[number] | null>((a, b) => (!a || b.priceCents < a.priceCents ? b : a), null);
  // Item-level free shipping is a home-market promise; abroad, items pay the rate.
  const shippable = zone?.isHome ? tl : tl.map((l) => ({ ...l, freeShipping: false }));
  const rates = offered.map((r) => ({ id: r.id, name: r.name, priceCents: shippingFor(r, shippable, subtotal, r.id === cheapest?.id), etaMinDays: r.etaMinDays, etaMaxDays: r.etaMaxDays }));
  const chosen = rates.find((r) => r.id === input.rateId) ?? rates[0] ?? null;

  const totals = computeTotals({
    lines: tl,
    coupon: convertCoupon(coupon?.rule ?? null, ctx),
    shippingCents: chosen?.priceCents ?? null,
    tax,
    money: { currency: ctx.code, locale: site.locale },
    step: centsStep(ctx.code),
  });
  if (cart?.couponCode && coupon?.error) totals.coupon = { code: cart.couponCode, applied: false, message: coupon.error };

  return {
    currency: ctx.code,
    exchangeRate: ctx.rate,
    lines,
    unavailable,
    rates,
    rateId: chosen?.id ?? null,
    totals,
    tax: tax ? { name: tax.name, rateBps: tax.rateBps } : null,
    paymentMethods: paymentMethods(site).map(({ id, label, description }) => ({ id, label, description })),
    shipsTo: rates.length > 0,
  };
}

// ── Place order ──────────────────────────────────────────────────────────────

export const hashOrderKey = (token: string) => createHash("sha256").update(token).digest("hex");

/**
 * Places an order from the cart in one transaction: re-prices every line, checks
 * the total the shopper saw, decrements stock only where enough remains (so two
 * shoppers can't buy the last item), records coupon use, creates a manual
 * PENDING payment and the first timeline event, and empties the cart.
 * Retrying with the same checkoutKey returns the original order.
 */
export async function placeOrder(owner: CartOwner, input: z.infer<typeof placeOrderSchema>) {
  const existing = await prisma.order.findUnique({ where: { checkoutKey: input.checkoutKey }, select: { id: true, orderNo: true } });
  if (existing) return { orderId: existing.id, orderNumber: formatOrderNumber(existing.orderNo), accessToken: null, replay: true };

  const site = await readSite();
  if (!owner.userId && !site.features.guestCheckout) throw new HttpError(401, "sign_in_required", "Sign in to check out.");

  const q = await quote(owner, { country: input.shippingAddress.country, region: input.shippingAddress.region, rateId: input.rateId, email: input.email });
  if (!q.lines.length) throw new HttpError(400, "empty_cart", "Your cart is empty.");
  if (q.unavailable.length) throw new HttpError(409, "unavailable_items", "Some items in your cart are no longer available. Review your cart and try again.");
  if (!q.shipsTo) throw new HttpError(400, "no_shipping", "We don't ship to that country yet.");
  const rate = q.rates.find((r) => r.id === input.rateId);
  if (!rate) throw new HttpError(400, "invalid_rate", "Choose a delivery option.", { rateId: ["Choose a delivery option."] });
  const provider = providerFor(input.paymentMethod, site);
  if (!provider) throw new HttpError(400, "invalid_payment", "Choose a payment method.", { paymentMethod: ["Choose a payment method."] });
  if (q.totals.coupon && !q.totals.coupon.applied) throw new HttpError(409, "coupon_invalid", q.totals.coupon.message ?? "Your promo code no longer applies.");
  if (q.totals.totalCents !== input.expectedTotalCents || (input.expectedCurrency && input.expectedCurrency !== q.currency)) {
    throw new HttpError(409, "total_changed", "Prices or availability changed while you were checking out. Review the updated total, then place your order.");
  }

  const cart = await findCart(owner);
  const guestToken = owner.userId ? null : randomBytes(24).toString("base64url");

  const order = await prisma.$transaction(async (tx) => {
    // Stock: conditional decrement; zero rows updated means someone else bought it first.
    for (const l of q.lines) {
      const updated = l.variantId
        ? await tx.productVariant.updateMany({ where: { id: l.variantId, stock: { gte: l.quantity }, product: { trackInventory: true } }, data: { stock: { decrement: l.quantity } } })
        : await tx.product.updateMany({ where: { id: l.productId, trackInventory: true, stock: { gte: l.quantity } }, data: { stock: { decrement: l.quantity } } });
      const tracked = await tx.product.findUnique({ where: { id: l.productId }, select: { trackInventory: true } });
      if (tracked?.trackInventory && updated.count === 0) {
        throw new HttpError(409, "out_of_stock", `${l.title}${l.variantTitle ? ` (${l.variantTitle})` : ""} just sold out. Update your cart and try again.`);
      }
      await tx.product.update({ where: { id: l.productId }, data: { soldCount: { increment: l.quantity } } });
    }
    if (q.totals.coupon?.applied) {
      const used = await tx.coupon.updateMany({
        where: { code: q.totals.coupon.code, OR: [{ maxUses: null }, { usedCount: { lt: prisma.coupon.fields.maxUses } }] },
        data: { usedCount: { increment: 1 } },
      });
      if (used.count === 0) throw new HttpError(409, "coupon_invalid", "That promo code has just been fully used.");
    }

    const created = await tx.order.create({
      data: {
        userId: owner.userId,
        email: input.email.trim().toLowerCase(),
        status: "PENDING",
        currency: q.currency,
        exchangeRate: new Prisma.Decimal(q.exchangeRate),
        subtotalCents: q.totals.subtotalCents,
        discountCents: q.totals.discountCents,
        shippingCents: q.totals.shippingCents,
        taxCents: q.totals.taxCents,
        totalCents: q.totals.totalCents,
        couponCode: q.totals.coupon?.applied ? q.totals.coupon.code : null,
        shippingAddress: input.shippingAddress as Prisma.InputJsonValue,
        billingAddress: (input.billingAddress ?? null) as Prisma.InputJsonValue,
        shippingMethod: { rateId: rate.id, name: rate.name, priceCents: rate.priceCents, etaMinDays: rate.etaMinDays, etaMaxDays: rate.etaMaxDays },
        guestAccessToken: guestToken ? hashOrderKey(guestToken) : null,
        checkoutKey: input.checkoutKey,
        notes: input.notes || null,
        items: {
          create: q.lines.map((l) => ({
            productId: l.productId,
            variantId: l.variantId,
            title: l.title,
            variantTitle: l.variantTitle,
            imageUrl: l.image?.url ?? null,
            unitPriceCents: l.unitPriceCents,
            quantity: l.quantity,
            totalCents: l.unitPriceCents * l.quantity,
          })),
        },
        events: { create: { status: "PENDING", note: "Order placed" } },
      },
      select: { id: true, orderNo: true },
    });
    const payment = await provider.initiate({ site, methodId: input.paymentMethod, amountCents: q.totals.totalCents, currency: q.currency, orderNumber: formatOrderNumber(created.orderNo) });
    await tx.payment.create({
      data: { orderId: created.id, provider: payment.provider, method: payment.method, status: payment.status, amountCents: q.totals.totalCents, currency: q.currency },
    });
    if (cart) {
      await tx.cartItem.deleteMany({ where: { cartId: cart.id, savedForLater: false } });
      await tx.cart.update({ where: { id: cart.id }, data: { couponCode: null } });
    }
    if (owner.userId && input.saveAddress) {
      const a = input.shippingAddress;
      const count = await tx.address.count({ where: { userId: owner.userId } });
      await tx.address.create({
        data: { userId: owner.userId, fullName: a.fullName, line1: a.line1, line2: a.line2 || null, city: a.city, region: a.region || null, postalCode: a.postalCode, country: a.country, phone: a.phone || null, isDefault: count === 0 },
      });
    }
    return created;
  });

  return { orderId: order.id, orderNumber: formatOrderNumber(order.orderNo), accessToken: guestToken, replay: false };
}
